use std::fs;
use std::path::Path;
use std::process::Command;

pub struct ProjectTemplate;

impl ProjectTemplate {
    pub fn create_project(target_dir: &Path, name: &str) -> Result<(), String> {
        fs::create_dir_all(target_dir).map_err(|e| e.to_string())?;

        fs::create_dir_all(target_dir.join("src")).map_err(|e| e.to_string())?;
        fs::create_dir_all(target_dir.join("tests")).map_err(|e| e.to_string())?;
        fs::create_dir_all(target_dir.join("assets")).map_err(|e| e.to_string())?;
        fs::create_dir_all(target_dir.join("build")).map_err(|e| e.to_string())?;

        let toml_content = format!(
            r#"[project]
name = "{}"
version = "1.0.0"
description = "My NEXA application"
authors = []

[language]
version = "1.0"

[build]
entry = "src/main.nexa"
target = "native"
optimization = "release"
output = "build"

[dependencies]

[dev-dependencies]
"#,
            name
        );
        fs::write(target_dir.join("nexa.toml"), toml_content).map_err(|e| e.to_string())?;

        let main_nexa = format!(
            r#"let app_name = "{}"

action greet(target) {{
    print("=== " + target + " ===")
    print("Welcome to NEXA Native World!")
}}

greet(app_name)
"#,
            name
        );
        fs::write(target_dir.join("src/main.nexa"), main_nexa).map_err(|e| e.to_string())?;

        let test_nexa = r#"let a = 10
var b = 20
b = b + a

if b == 30 {
    print("TEST PASS: b == 30")
} else {
    print("TEST FAIL")
}
"#;
        fs::write(target_dir.join("tests/test_main.nexa"), test_nexa).map_err(|e| e.to_string())?;

        let gitignore = r#"/build/
nexa.lock.bk
*.s
"#;
        fs::write(target_dir.join(".gitignore"), gitignore).map_err(|e| e.to_string())?;

        let lockfile_content = r#"# This file is automatically generated by NEXA Project System.
# Manual editing is not recommended.

version = 1
"#;
        fs::write(target_dir.join("nexa.lock"), lockfile_content).map_err(|e| e.to_string())?;

        let _ = Command::new("git")
            .arg("init")
            .current_dir(target_dir)
            .output();

        Ok(())
    }
}
