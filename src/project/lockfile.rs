use serde::{Deserialize, Serialize};
use std::fs;
use std::path::Path;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Lockfile {
    #[serde(default = "default_lock_version")]
    pub version: u32,
    #[serde(default, rename = "package")]
    pub packages: Vec<LockedPackage>,
}

fn default_lock_version() -> u32 {
    1
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    pub source: String,
    pub checksum: String,
    #[serde(default)]
    pub dependencies: Vec<String>,
}

impl Default for Lockfile {
    fn default() -> Self {
        Self::new()
    }
}

impl Lockfile {
    pub fn new() -> Self {
        Self {
            version: 1,
            packages: Vec::new(),
        }
    }

    pub fn load(path: &Path) -> Result<Option<Self>, String> {
        if !path.exists() {
            return Ok(None);
        }
        let content = fs::read_to_string(path)
            .map_err(|e| format!("Failed to read lockfile '{}': {}", path.display(), e))?;
        let lockfile: Lockfile = toml::from_str(&content)
            .map_err(|e| format!("Corrupted lockfile '{}':\n{}", path.display(), e))?;
        Ok(Some(lockfile))
    }

    pub fn save(&self, path: &Path) -> Result<(), String> {
        let header = "# This file is automatically generated by NEXA Project System.\n# Manual editing is not recommended.\n\n";
        let body = toml::to_string_pretty(self)
            .map_err(|e| format!("Failed to serialize lockfile: {}", e))?;
        let full = format!("{}{}", header, body);
        fs::write(path, full)
            .map_err(|e| format!("Failed to write lockfile '{}': {}", path.display(), e))?;
        Ok(())
    }

    /// Verify that every expected package is present and unchanged.
    pub fn verify(&self, expected: &[LockedPackage]) -> Result<(), String> {
        for want in expected {
            let found = self.packages.iter().find(|p| p.name == want.name);
            match found {
                None => {
                    return Err(format!(
                        "Lockfile is missing package '{}'. Run 'nexa update'.",
                        want.name
                    ));
                }
                Some(got) => {
                    let mut got_deps = got.dependencies.clone();
                    let mut want_deps = want.dependencies.clone();
                    got_deps.sort();
                    want_deps.sort();
                    if got.version != want.version
                        || got.source != want.source
                        || got.checksum != want.checksum
                        || got_deps != want_deps
                    {
                        return Err(format!(
                            "Lockfile entry for '{}' is out of date. Run 'nexa update'.",
                            want.name
                        ));
                    }
                }
            }
        }
        Ok(())
    }

    pub fn compute_checksum(data: &[u8]) -> String {
        let mut hash: u64 = 0xcbf29ce484222325;
        for &byte in data {
            hash ^= byte as u64;
            hash = hash.wrapping_mul(0x100000001b3);
        }
        format!("{:016x}", hash)
    }
}
